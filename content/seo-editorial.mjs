function commercial(page) {
  const hasAiAct = (page.sources ?? []).some((source) =>
    [EU_AI_ACT.url, EU_AI_ACT_EN.url].includes(source.url),
  );
  const hasDataProtection = (page.sources ?? []).some((source) =>
    [EDPB.url, EDPB_EN.url, PRIVACY.url, PRIVACY_EN.url].includes(source.url),
  );
  const regulatoryIntro =
    hasAiAct && hasDataProtection
      ? page.lang === "it"
        ? "AI Act e GDPR possono applicarsi insieme: requisiti e misure dipendono dal ruolo dell’organizzazione, dai dati e dall’uso effettivo del sistema. La valutazione precede quindi la configurazione."
        : "The AI Act and GDPR can apply together: duties and safeguards depend on the organisation’s role, the data and the system’s actual use. Assessment therefore comes before configuration."
      : page.lang === "it"
        ? "I requisiti dipendono dal ruolo dell’organizzazione, dai dati e dall’uso effettivo del sistema. Per questo la valutazione precede la configurazione."
        : "Requirements depend on the organisation’s role, the data and the system’s actual use. That is why assessment comes before configuration.";
  return {
    kind: "commercial",
    labels: page.lang === "it" ? itLabels : enLabels,
    steps: page.steps ?? (page.lang === "it" ? itProjectSteps : enProjectSteps),
    sourcesTitle: page.lang === "it" ? "Riferimenti per progettare con criterio" : "References for responsible design",
    sourcesIntro: regulatoryIntro,
    sourceDisclaimer: page.lang === "it" ? itDisclaimer : enDisclaimer,
    ...page,
  };
}

function editorial(page) {
  return {
    kind: page.kind ?? "editorial",
    labels: page.lang === "it" ? itLabels : enLabels,
    sourceDisclaimer: page.lang === "it" ? itDisclaimer : enDisclaimer,
    ...page,
  };
}

