import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

// Keep filenames compatible with static hosting; normalize only published URLs.
const root = new URL('../public/', import.meta.url);
async function files(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  return (await Promise.all(entries.map(e => e.isDirectory() ? files(new URL(`${e.name}/`, dir)) : new URL(e.name, dir)))).flat();
}
const htmlFiles = (await files(root)).filter(f => f.pathname.endsWith('.html'));
const paths = htmlFiles.map(f => '/' + path.relative(root.pathname, f.pathname)).filter(p => !p.endsWith('/index.html') && p !== '/404.html');
const replacements = paths.sort((a, b) => b.length - a.length);
for (const file of htmlFiles) {
  const original = await readFile(file, 'utf8');
  let result = original;
  for (const old of replacements) result = result.replaceAll(old, old.slice(0, -5));
  if (result !== original) await writeFile(file, result);
}
await writeFile(new URL('_redirects', root), '# Canonical static-page URLs. Generated by normalize-seo-urls.mjs.\n' + paths.map(p => `${p} ${p.slice(0, -5)} 301`).join('\n') + '\n');
console.log(`Canonical URLs normalized across ${htmlFiles.length} HTML pages.`);
